-- 1. Tabela de Trechos da Rodovia
CREATE TABLE tb_trecho_rodovia (
                                   id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   km NUMBER NOT NULL,
                                   altura_vegetacao NUMBER(5,2) NOT NULL,
                                   umidade NUMBER(5,2) NOT NULL,
                                   possui_sensor NUMBER(1) NOT NULL
);

-- 2. Tabela de Equipes de Manutenção
CREATE TABLE tb_equipe_manutencao (
                                      id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      nome VARCHAR2(100) NOT NULL,
                                      especialidade VARCHAR2(100) NOT NULL,
                                      disponivel NUMBER(1) NOT NULL
);

-- 3. Tabela de Histórico de Relatórios
CREATE TABLE tb_relatorio_prioridade (
                                         id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         qt_urgente NUMBER NOT NULL,
                                         qt_critico NUMBER NOT NULL,
                                         qt_atencao NUMBER NOT NULL,
                                         qt_normal NUMBER NOT NULL,
                                         resumo VARCHAR2(500) NOT NULL,
                                         data_geracao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. Tabela de Intervenções Operacionais (Pulverização e Roçada)
CREATE TABLE tb_intervencao_operacional (
                                            id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            tipo VARCHAR2(50) NOT NULL,
                                            km_trecho NUMBER NOT NULL,
                                            status VARCHAR2(50) NOT NULL,
                                            data_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);